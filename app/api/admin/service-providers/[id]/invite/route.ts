import crypto from "node:crypto";

import mongoose from "mongoose";
import { NextResponse } from "next/server";

import { getAuthSession } from "@/lib/auth";
import { connectDB } from "@/lib/db";
import ServiceProvider from "@/lib/models/ServiceProvider";
import ServiceProviderOutreachEvent from "@/lib/models/ServiceProviderOutreachEvent";
import { hashServiceProviderInviteToken } from "@/lib/service-provider-invites";

type RouteContext = {
  params: { id: string };
};

export async function POST(_: Request, { params }: RouteContext) {
  const session = await getAuthSession();
  if (!session?.user) {
    return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
  }
  if (session.user.role !== "admin") {
    return NextResponse.json({ error: "Forbidden" }, { status: 403 });
  }
  if (!mongoose.isValidObjectId(params.id)) {
    return NextResponse.json({ error: "Invalid service provider id" }, { status: 400 });
  }

  await connectDB();

  const provider = await ServiceProvider.findById(params.id).exec();
  if (!provider) {
    return NextResponse.json({ error: "Service provider not found" }, { status: 404 });
  }

  if (provider.status !== "unclaimed" || provider.userId) {
    return NextResponse.json(
      { error: "Invite links can only be generated for unclaimed providers." },
      { status: 409 },
    );
  }

  const rawToken = crypto.randomBytes(32).toString("hex");
  const now = new Date();

  provider.inviteTokenHash = hashServiceProviderInviteToken(rawToken);
  provider.inviteTokenExpiresAt = new Date(now.getTime() + 7 * 24 * 60 * 60 * 1000);
  provider.contactStatus = "invited";
  provider.contactedAt = now;
  await provider.save();

  await ServiceProviderOutreachEvent.create({
    providerId: provider._id,
    type: "invite_sent",
    notes: "Invite link generated by admin",
    createdBy: session.user.id,
    createdAt: now,
  });

  return NextResponse.json({ claimUrl: `/claim/provider/${rawToken}` });
}
